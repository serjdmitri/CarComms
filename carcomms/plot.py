"""Draw a swim-lane timeline of a simulation as a standalone SVG (no dependencies)."""

from __future__ import annotations

from typing import List, Sequence, Tuple
from xml.sax.saxutils import escape

from .simulation import SimResult

BG = "#ffffff"
INK = "#1f2937"
MUTED = "#6b7280"
WAIT = "#f59e0b"
CROSS = {"car_a": "#2563eb", "car_b": "#059669"}
GRID = "#e5e7eb"


def timeline_svg(panels: Sequence[Tuple[str, SimResult]], t_max: float = 6.0, width: int = 900) -> str:
    left, right, lane_h, pad, head = 110, 24, 34, 14, 46
    plot_w = width - left - right
    height = 30
    for _, _ in panels:
        height += head + 2 * lane_h + pad + 22
    height += 24

    def x(t: float) -> float:
        return left + min(max(t, 0.0), t_max) / t_max * plot_w

    out: List[str] = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
        f'role="img" aria-label="Timeline of waiting and crossing for two cars under two policies">',
        f'<rect width="{width}" height="{height}" rx="14" fill="{BG}" stroke="{GRID}"/>',
        '<style>text{font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif}</style>',
        f'<text x="{left}" y="24" font-size="13" fill="{MUTED}">Simulation. Amber = waiting at the stop line, solid = inside the intersection.</text>',
    ]
    y0 = 36
    for title, res in panels:
        out.append(f'<text x="18" y="{y0 + 22}" font-size="15" font-weight="700" fill="{INK}">{escape(title)}</text>')
        y = y0 + head
        # time grid
        step = 1.0
        t = 0.0
        while t <= t_max + 1e-9:
            out.append(f'<line x1="{x(t):.1f}" y1="{y - 6}" x2="{x(t):.1f}" y2="{y + 2 * lane_h + 2}" stroke="{GRID}"/>')
            out.append(f'<text x="{x(t):.1f}" y="{y + 2 * lane_h + 16}" font-size="10" fill="{MUTED}" text-anchor="middle">{t:.0f} s</text>')
            t += step
        for i, vid in enumerate(("car_a", "car_b")):
            ly = y + i * lane_h
            out.append(f'<text x="18" y="{ly + 20}" font-size="12" fill="{INK}">{vid}</text>')
            for trip in (t for t in res.trips if t.vehicle == vid):
                enter = trip.enter if trip.enter is not None else t_max
                exit_ = trip.exit if trip.exit is not None else t_max
                if enter > trip.arrive:
                    out.append(f'<rect x="{x(trip.arrive):.1f}" y="{ly + 4}" width="{max(x(enter) - x(trip.arrive), 1):.1f}" '
                               f'height="20" rx="4" fill="{WAIT}" opacity="0.85"/>')
                if trip.enter is not None:
                    out.append(f'<rect x="{x(enter):.1f}" y="{ly + 4}" width="{max(x(exit_) - x(enter), 1):.1f}" '
                               f'height="20" rx="4" fill="{CROSS[vid]}"/>')
                    label = f"priority {trip.priority}" if trip.priority else "normal"
                    if x(exit_) - x(enter) > 70:
                        out.append(f'<text x="{x(enter) + 8:.1f}" y="{ly + 18}" font-size="11" fill="#fff">{label}</text>')
                out.append(f'<path d="M{x(trip.arrive):.1f} {ly + 2} l-4 -6 h8 z" fill="{INK}"/>')
        y0 += head + 2 * lane_h + pad + 22
    out.append(f'<text x="{left}" y="{height - 10}" font-size="10" fill="{MUTED}">Triangle = reached the stop line. '
               f'Generated by `python3 -m carcomms plot`.</text>')
    out.append("</svg>")
    return "\n".join(out)
